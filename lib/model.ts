// Token Radar — the value model (model "tide-1").
//
// One sealed snapshot in, one ranked board out. The board covers every slug in the
// snapshot's watchlist (the floor, never a ceiling) and fills the remaining rows with
// the highest-implied pre-token protocols below the floor: the early radar.
//
// A protocol is pre-token when its record carries no token at all (no market cap, no
// CoinGecko id, no symbol). Live-token protocols are never ranked; the dashboard shows
// them apart with the market cap the market itself gives them, never a model number.
//
// Implied value is one deterministic function of the snapshot's own figures:
//
//   base      = tvl_usd x 0.20
//   growth    = clamp(change_7d, -50, 100)            (per cent, 7 days)
//   growthMul = 1 + (growth / 100) x 0.70
//   tenure    = 0.55 + min(age_days, 1460) / 1460 x 0.45
//               age_days = days from listed_at to the snapshot's as_of;
//               unknown listed_at counts as 180 days
//   breadth   = 1 + 0.04 x min(chains.length, 5)      (multi-chain reach)
//   implied   = max(1, round(base x growthMul x tenure x breadth))
//
// Why these four terms: TVL is the size of the record so far; seven-day growth is its
// direction; tenure is how long the protocol has run with no token (a long wait with a
// large TVL is the launch the radar exists to catch); breadth is how many chains the
// record spans. No protocol name is ever special-cased: the same function scores every
// row, and the constants above are the whole model.
//
// Strict order: whole-dollar rounding can tie two protocols, so after sorting the
// board is walked once and a row that ties or beats the row above it is written one
// dollar lower. The ranking is therefore strictly decreasing, and a reader can trust
// that rank 1 really is the board's most valuable protocol.

/** One protocol entry of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  tenure_floor: number;
  tenure_range: number;
  tenure_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.2,
  growth_weight: 0.7,
  growth_floor: -50,
  growth_cap: 100,
  tenure_floor: 0.55,
  tenure_range: 0.45,
  tenure_days: 1460,
  unknown_age_days: 180,
  breadth_step: 0.04,
  breadth_max_chains: 5,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'tide-1';

/** How many pre-token protocols below the watchlist floor the early radar carries. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

